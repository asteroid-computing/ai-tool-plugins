package main

import (
	"reflect"
	"testing"
)

const findSrc = `//go:build linux

// Package p keeps the log (ADR 0004, decision 6).
package p

/*
#cgo LDFLAGS: -lm (#12)
#include <math.h>
*/
import "C"

//go:generate stringer -type=Kind (#34)

// Kind is a kind of event; see golang/go#22682.
type Kind int

func f() {
	// The check runs under the mutex, so two writers cannot both append.
	_ = 1 // this used to be 2
}

func ExampleKind() {
	// Output:
	// see #42
}
`

func TestFindCandidates(t *testing.T) {
	got, err := findCandidates("p.go", []byte(findSrc))
	if err != nil {
		t.Fatal(err)
	}
	want := []match{
		{Line: 3, Text: "// Package p keeps the log (ADR 0004, decision 6)."},
		{Line: 14, Text: "// Kind is a kind of event; see golang/go#22682."},
		{Line: 19, Text: "// this used to be 2"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("findCandidates() = %#v, want %#v", got, want)
	}
}

func TestIsDirective(t *testing.T) {
	tests := map[string]bool{
		"//go:build linux":              true,
		"// +build linux":               true,
		"//go:generate stringer (#34)":  true,
		"//line foo.go:10":              true,
		"/*line foo.go:10*/":            true,
		"//export Add":                  true,
		"//nolint:errcheck // see #12":  true,
		"// go:build is not one":        false,
		"// Kind is a kind (#12).":      false,
		"// TODO(aj): tidy this (#12).": false,
	}
	for text, want := range tests {
		if got := isDirective(text); got != want {
			t.Errorf("isDirective(%q) = %v, want %v", text, got, want)
		}
	}
}

func TestFindCandidatesSkipsGeneratedFiles(t *testing.T) {
	src := "// Code generated by stringer; DO NOT EDIT.\n\n// Package p (#12).\npackage p\n"
	got, err := findCandidates("p.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 0 {
		t.Errorf("findCandidates() = %#v, want none", got)
	}
}

func TestDiffBeyondComments(t *testing.T) {
	const old = `//go:build linux

// Package p keeps the log (#12).
package p

/*
#include <math.h>
*/
import "C"

// F returns one (decision 3).
func F() int {
	// A comment that only restates the code.
	return 1 // one
}
`
	tests := []struct {
		name string
		cur  string
		want string
	}{
		{"comments only", `//go:build linux

// Package p keeps the log.
package p

/*
#include <math.h>
*/
import "C"

// F returns one.
func F() int {
	return 1
}
`, ""},
		{"code changed", `//go:build linux

// Package p keeps the log.
package p

/*
#include <math.h>
*/
import "C"

// F returns one.
func F() int {
	return 2
}
`, "code changed, from line 13"},
		{"directive changed", `//go:build darwin

// Package p keeps the log (#12).
package p

/*
#include <math.h>
*/
import "C"

// F returns one (decision 3).
func F() int {
	// A comment that only restates the code.
	return 1 // one
}
`, "directives changed"},
		{"cgo preamble changed", `//go:build linux

// Package p keeps the log (#12).
package p

/*
#include <stdio.h>
*/
import "C"

// F returns one (decision 3).
func F() int {
	// A comment that only restates the code.
	return 1 // one
}
`, "cgo preamble changed"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := diffBeyondComments("p.go", []byte(old), []byte(tt.cur))
			if err != nil {
				t.Fatal(err)
			}
			if got != tt.want {
				t.Errorf("diffBeyondComments() = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestDiffBeyondCommentsGeneratedFile(t *testing.T) {
	old := "// Code generated by stringer; DO NOT EDIT.\n\npackage p\n\n// K (#1).\nconst K = 1\n"
	cur := "// Code generated by stringer; DO NOT EDIT.\n\npackage p\n\n// K.\nconst K = 1\n"
	got, err := diffBeyondComments("p.go", []byte(old), []byte(cur))
	if err != nil {
		t.Fatal(err)
	}
	if got != "generated file changed" {
		t.Errorf("diffBeyondComments() = %q, want %q", got, "generated file changed")
	}
}
